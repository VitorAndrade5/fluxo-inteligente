CREATE TABLE floors (
    id           SMALLINT PRIMARY KEY,
    code         TEXT     NOT NULL UNIQUE,
    name         TEXT     NOT NULL,
    level        SMALLINT NOT NULL,
    plan_image   TEXT     NOT NULL,
    aspect_ratio DOUBLE PRECISION NOT NULL
);

CREATE TABLE sectors (
    id    SMALLINT PRIMARY KEY,
    code  TEXT NOT NULL UNIQUE,
    name  TEXT NOT NULL,
    color TEXT NOT NULL
);

CREATE TABLE zones (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           TEXT     NOT NULL UNIQUE,
    floor_id       SMALLINT NOT NULL REFERENCES floors(id),
    sector_id      SMALLINT NOT NULL REFERENCES sectors(id),
    name           TEXT     NOT NULL,
    store_ref      TEXT,
    x_pct          DOUBLE PRECISION NOT NULL CHECK (x_pct BETWEEN 0 AND 100),
    y_pct          DOUBLE PRECISION NOT NULL CHECK (y_pct BETWEEN 0 AND 100),
    radius_pct     DOUBLE PRECISION NOT NULL DEFAULT 4,
    capacity_hour  INTEGER  NOT NULL CHECK (capacity_hour > 0),
    attractiveness DOUBLE PRECISION NOT NULL DEFAULT 1,
    is_entrance    SMALLINT NOT NULL DEFAULT 0 CHECK (is_entrance IN (0, 1)),
    connects_to    TEXT
);
CREATE INDEX ix_zones_floor ON zones(floor_id);

CREATE TABLE cameras (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id     INTEGER NOT NULL REFERENCES zones(id),
    external_id TEXT    NOT NULL UNIQUE,
    name        TEXT    NOT NULL,
    active      SMALLINT NOT NULL DEFAULT 1
);

CREATE TABLE visitors (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id   TEXT        NOT NULL UNIQUE,
    first_seen TIMESTAMP   NOT NULL
);

CREATE TABLE movement_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visitor_id   BIGINT    NOT NULL REFERENCES visitors(id),
    from_zone_id INTEGER   REFERENCES zones(id),
    to_zone_id   INTEGER   NOT NULL REFERENCES zones(id),
    camera_id    INTEGER   REFERENCES cameras(id),
    occurred_at  TIMESTAMP NOT NULL,
    source       TEXT      NOT NULL DEFAULT 'api' CHECK (source IN ('api', 'simulator', 'monuv')),
    created_at   TIMESTAMP NOT NULL DEFAULT now(),
    CHECK (from_zone_id IS NULL OR from_zone_id <> to_zone_id)
);

CREATE INDEX ix_events_time    ON movement_events(occurred_at);
CREATE INDEX ix_events_visitor ON movement_events(visitor_id, occurred_at);
CREATE INDEX ix_events_to_zone ON movement_events(to_zone_id, occurred_at);

CREATE TABLE zone_hourly_stats (
    zone_id      INTEGER   NOT NULL REFERENCES zones(id),
    bucket_start TIMESTAMP NOT NULL,
    entries      INTEGER   NOT NULL DEFAULT 0,
    PRIMARY KEY (zone_id, bucket_start)
);
CREATE INDEX ix_stats_bucket ON zone_hourly_stats(bucket_start);

CREATE TABLE users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL,
    email         TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL DEFAULT 'gestor' CHECK (role IN ('admin', 'gestor')),
    created_at    TIMESTAMP NOT NULL DEFAULT now()
);
