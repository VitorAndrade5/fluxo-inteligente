-- Fluxo Inteligente · esquema para PostgreSQL 14+ (produção: Neon/Vercel)
-- Mesmo modelo de schema.sql com tipos nativos. É executado pelo backend
-- (app/database.py) quando o banco ainda não tem as tabelas.
-- seed.sql e queries.sql são compartilhados com o SQLite; consultas que
-- divergem têm a variante "@postgres" em queries.sql.
--
-- Quando o volume crescer: particionar movement_events por mês
-- (PARTITION BY RANGE (occurred_at)) e arquivar meses antigos.
