CREATE TABLE parking_lots (
    id          SMALLINT PRIMARY KEY,
    code        TEXT     NOT NULL UNIQUE,
    name        TEXT     NOT NULL,
    level_label TEXT     NOT NULL,
    total       INTEGER  NOT NULL CHECK (total > 0),
    rows_count  INTEGER  NOT NULL,
    cols_count  INTEGER  NOT NULL,
    is_estimate SMALLINT NOT NULL DEFAULT 0 CHECK (is_estimate IN (0, 1)),
    preference  DOUBLE PRECISION NOT NULL DEFAULT 1
);

CREATE TABLE parking_spaces (
    id      INTEGER  PRIMARY KEY,
    lot_id  SMALLINT NOT NULL REFERENCES parking_lots(id),
    code    TEXT     NOT NULL UNIQUE,
    row_idx INTEGER  NOT NULL,
    col_idx INTEGER  NOT NULL,
    kind    TEXT     NOT NULL DEFAULT 'comum'
            CHECK (kind IN ('comum', 'pne', 'idoso', 'neurodiverso', 'gestante'))
);
CREATE INDEX ix_spaces_lot ON parking_spaces(lot_id);

CREATE TABLE parking_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id    INTEGER   NOT NULL REFERENCES parking_spaces(id),
    occupied    SMALLINT  NOT NULL CHECK (occupied IN (0, 1)),
    occurred_at TIMESTAMP NOT NULL,
    source      TEXT      NOT NULL DEFAULT 'api' CHECK (source IN ('api', 'simulator', 'sensor', 'visao')),
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX ix_parking_events_space ON parking_events(space_id, occurred_at);
CREATE INDEX ix_parking_events_time  ON parking_events(occurred_at);
